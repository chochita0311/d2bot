#[test]
fn gzip_fixture_rejects_invalid_or_truncated_data() -> TestResult {
    use std::io::Write;
    let mut encoder = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::default());
    encoder.write_all(br#"{"expected":null}"#)?;
    let bytes = encoder.finish()?;
    assert_eq!(support::decode_fixture(&bytes)?, json!({"expected":null}));
    assert!(support::decode_fixture(b"invalid").is_err());
    assert!(support::decode_fixture(&bytes[..bytes.len() - 3]).is_err());
    let mut trailing = bytes.clone();
    trailing.push(0);
    assert!(support::decode_fixture(&trailing).is_err());
    let mut concatenated = bytes.clone();
    concatenated.extend_from_slice(&bytes);
    assert!(support::decode_fixture(&concatenated).is_err());
    Ok(())
}

#[test]
fn generated_tables_and_frozen_fixture_inventory_keep_reviewed_hashes() -> TestResult {
    use sha2::{Digest, Sha256};
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let owner = root.join("tests/fixtures/legacy-baseline");
    let provenance: serde_json::Value =
        serde_json::from_slice(&fs::read(owner.join("provenance.json"))?)?;
    for table in provenance["generated_tables"]
        .as_array()
        .ok_or("generated table inventory")?
    {
        let path = table["path"].as_str().ok_or("table path")?;
        let source = fs::read_to_string(root.join(path))?.replace("\r\n", "\n");
        assert_eq!(
            format!("{:x}", Sha256::digest(source.as_bytes())),
            table["sha256_lf"],
            "{path}"
        );
    }
    let manifest: serde_json::Value =
        serde_json::from_slice(&fs::read(owner.join("manifest.json"))?)?;
    let mut listed = std::collections::BTreeSet::new();
    for entry in manifest["files"]
        .as_array()
        .ok_or("frozen fixture inventory")?
    {
        let path = entry["path"].as_str().ok_or("fixture path")?;
        assert!(listed.insert(path.to_owned()), "duplicate fixture: {path}");
        assert!(
            Path::new(path)
                .components()
                .all(|part| matches!(part, std::path::Component::Normal(_)))
        );
        let bytes = fs::read(owner.join(path))?;
        assert_eq!(
            bytes.len() as u64,
            entry["bytes"].as_u64().ok_or("fixture size")?,
            "{path}"
        );
        assert_eq!(
            format!("{:x}", Sha256::digest(&bytes)),
            entry["sha256"],
            "{path}"
        );
    }
    fn collect(
        owner: &Path,
        path: &Path,
        files: &mut std::collections::BTreeSet<String>,
    ) -> TestResult {
        for item in fs::read_dir(path)? {
            let path = item?.path();
            if path.is_dir() {
                collect(owner, &path, files)?;
            } else if path.extension().is_some_and(|e| e == "gz") {
                files.insert(
                    path.strip_prefix(owner)?
                        .to_string_lossy()
                        .replace('\\', "/"),
                );
            }
        }
        Ok(())
    }
    let mut actual = std::collections::BTreeSet::new();
    collect(&owner, &owner, &mut actual)?;
    assert_eq!(
        actual, listed,
        "frozen fixture inventory has missing or extra files"
    );
    Ok(())
}

#[test]
fn generated_file_identity_is_portable_and_detects_changed_or_truncated_bytes() -> TestResult {
    let a = directory::TestDirectory::new()?;
    let b = directory::TestDirectory::new()?;
    let first = a.path().join("video.avi");
    let second = b.path().join("video.avi");
    fs::write(&first, b"RIFF identical generated bytes")?;
    fs::write(&second, b"RIFF identical generated bytes")?;
    let identity = |path: &Path| {
        let request = json!({"paths":[path]});
        support::Case::new(&request).identity("recording-oracle", &request)
    };
    assert_eq!(identity(&first)?, identity(&second)?);
    fs::write(&second, b"RIFF changed generated bytes")?;
    assert_ne!(identity(&first)?, identity(&second)?);
    fs::write(&second, b"RIFF")?;
    assert_ne!(identity(&first)?, identity(&second)?);
    Ok(())
}

#[test]
fn config_identity_ignores_docs_but_preserves_json_order_and_contents() -> TestResult {
    let directory = directory::TestDirectory::new()?;
    let path = directory.path().join("config.json");
    let request = json!({"config_path":directory.path()});
    let identity = || support::Case::new(&request).identity("config-oracle", &request);
    fs::write(&path, b"{\"z\":0,\"a\":1}")?;
    let original = identity()?;
    fs::write(directory.path().join("README.md"), b"documentation only")?;
    assert_eq!(original, identity()?);
    fs::write(&path, b"{\"a\":1,\"z\":0}")?;
    assert_ne!(original, identity()?);
    fs::write(&path, b"{\"z\":0,\"a\":2}")?;
    assert_ne!(original, identity()?);
    Ok(())
}

#[test]
fn path_markers_literal_dollars_and_error_representations_roundtrip() {
    let root = env!("CARGO_MANIFEST_DIR");
    let request =
        json!({"path":Path::new(root).join("target/tmp/baseline-marker-case/missing.json")});
    let case = support::Case::new(&request);
    let original = json!({"literal":"$ROOT $EXTROOT $TEMP0 $ROOT:backslash \u{1e}D", "plain":root,"repr":root.replace('\\',"\\\\"),"request":request});
    assert_eq!(case.value(&case.value(&original, false), true), original);
}

