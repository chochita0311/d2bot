#[test]
fn checkout_has_no_project_python_source_or_environment() -> TestResult {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    for retired in [
        "main.py",
        "diablo2",
        "requirements.txt",
        "pyproject.toml",
        ".venv",
        ".tools/virtualenv",
        ".tools/virtualenv-appdata",
    ] {
        assert!(
            !root.join(retired).exists(),
            "retired project path still exists: {retired}"
        );
    }
    fn check(path: &Path) -> TestResult {
        for item in fs::read_dir(path)? {
            let path = item?.path();
            if path.is_dir() {
                check(&path)?;
            } else {
                assert!(
                    !path.extension().is_some_and(|ext| matches!(
                        ext.to_str(),
                        Some("py" | "pyw" | "pyi" | "pyc" | "pyd")
                    )),
                    "Python artifact: {}",
                    path.display()
                );
            }
        }
        Ok(())
    }
    for directory in ["src", "tests", "scripts", "examples"] {
        check(&root.join(directory))?;
    }
    Ok(())
}

#[test]
fn state_file_arguments_bind_the_existing_reference_state() -> TestResult {
    let directory = directory::TestDirectory::new()?;
    let path = directory.path().join("reference-state.json");
    let request = json!([{"op":"town-step","arguments":["--state",path]}]);
    let identity = || support::Case::new(&request).identity("tools-oracle", &request);
    let missing = identity()?;
    fs::write(&path, b"{\"phase\":1}")?;
    let first = identity()?;
    assert_ne!(first, missing);
    fs::write(&path, b"{\"phase\":2}")?;
    assert_ne!(first, identity()?);
    Ok(())
}
